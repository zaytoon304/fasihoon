function shuffleAsas(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// يبني 3 مضلِّلات لعنصر مستهدف: حروف تشابه بصري حقيقي إن وُجدت، وإلا عشوائي من نفس المرحلة
function asasDistractors(stage, targetIndex) {
  const items = stage.items;
  const pool = new Set();

  if (stage.kind === "letter") {
    const group = ASAS_SIMILAR_GROUPS.find((g) => g.includes(targetIndex));
    if (group) group.forEach((i) => { if (i !== targetIndex) pool.add(i); });
  }

  const allIdx = shuffleAsas(items.map((_, i) => i).filter((i) => i !== targetIndex && !pool.has(i)));
  let need = 3 - pool.size;
  for (const i of allIdx) {
    if (need <= 0) break;
    pool.add(i);
    need--;
  }

  return Array.from(pool).slice(0, 3).map((i) => items[i]);
}
